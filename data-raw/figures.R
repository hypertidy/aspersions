# Rscript data-raw/figures.R : the README figures, into man/figures/ (needs ximage)
library(aspersions)
library(ximage)
## volcano, georeferenced: Maungawhau, Auckland, New Zealand Map Grid (EPSG:27200), 10 m
z <- volcano[nrow(volcano):1, ncol(volcano):1]
ex <- c(2667400, 2668010, 6478700, 6479570)
eye <- c(2667700, 6479100)
grey <- grey.colors(64, 0.25, 0.95)

png("man/figures/viewshed.png", width = 1400, height = 760, res = 140)
layout(matrix(1:2, 1), widths = c(0.42, 0.58))
par(mar = c(1, 1, 2.5, 1))
v <- viewshed(z, ex, eye, eye = 1.5)
ximage(z, extent = ex, col = grey, asp = 1, axes = FALSE, main = "Visible from 1.5 m")
ximage(v$visible, extent = ex, add = TRUE, col = c("transparent", adjustcolor("gold", 0.75)), breaks = c(-1, 0.01, 2))
xcontour(z, extent = ex, add = TRUE, col = adjustcolor("black", 0.25))
## outline the visible pieces in a 100 m window about 200 m from the eye
d <- sqrt((v$pieces$x - eye[1])^2 + (v$pieces$y - eye[2])^2)
cen <- unlist(v$pieces[which.min(abs(d - 200)), c("x", "y")])
w <- c(cen[1] - 50, cen[1] + 50, cen[2] - 50, cen[2] + 50)
win <- v$pieces[v$pieces$x > w[1] & v$pieces$x < w[2] & v$pieces$y > w[3] & v$pieces$y < w[4], ]
for (p in split(win, win$piece)) polygon(p$x, p$y, border = adjustcolor("black", 0.5), lwd = 0.5)
rect(w[1], w[3], w[2], w[4], lty = 3)
points(eye[1], eye[2], pch = 21, bg = "orangered", cex = 1.6)
v30 <- viewshed(z, ex, eye, eye = 30, pieces = FALSE)
par(mar = c(4, 4, 2.5, 1))
plot(v$skyline, type = "n", xlab = "azimuth (degrees from grid north)", ylab = "horizon elevation (degrees)",
     main = "Skyline from the same spot", xaxt = "n", ylim = range(c(v$skyline$elevation, v30$skyline$elevation)))
axis(1, at = seq(0, 360, by = 90), labels = c("N", "E", "S", "W", "N"))
polygon(c(0, v$skyline$azimuth, 359), c(-90, v$skyline$elevation, -90), col = "darkolivegreen3", border = "darkolivegreen")
lines(v30$skyline, lty = 2)
legend("topright", c("eye 1.5 m", "eye 30 m"), fill = c("darkolivegreen3", NA), border = c("darkolivegreen", NA), lty = c(NA, 2), bty = "n")
dev.off()

png("man/figures/shade.png", width = 1400, height = 900, res = 140)
par(mfrow = c(1, 2), mar = c(1, 1, 3, 1))
s <- cast_shade(z, ex, azimuth = 300, elevation = 12)
ximage(z, extent = ex, col = grey, asp = 1, axes = FALSE, main = "Cast shade:\nsun from 300 degrees, 12 degrees up")
ximage(s * 1, extent = ex, add = TRUE, col = c(NA, adjustcolor("midnightblue", 0.6)))
h <- sun_hours(z, ex, "2026-06-21", lon = 174.764, lat = -36.876, tz = "Pacific/Auckland", step = 5)
ximage(h, extent = ex, col = hcl.colors(64, "Inferno"), asp = 1, axes = FALSE,
       main = sprintf("Hours of direct sun, 21 June\n(of %.1f h daylight)", attr(h, "daylight")))
xcontour(z, extent = ex, add = TRUE, col = adjustcolor("white", 0.3))
dev.off()
cat("ok\n")
